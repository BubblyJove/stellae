                    label = "Time",
                    value = formatSeconds(elapsedSeconds),
                    color = TextPrimary,
                    modifier = Modifier.weight(1f)
                )
            }
        }

        Spacer(modifier = Modifier.height(32.dp))

        PrimaryButton(
            text = "Return",
            onClick = onBack,
            modifier = Modifier.fillMaxWidth()
        )
    }
