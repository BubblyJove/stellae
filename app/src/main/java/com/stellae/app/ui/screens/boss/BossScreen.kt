    onRetry: () -> Unit,
    onBack: () -> Unit
) {
    Column(
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.Center,
        modifier = Modifier
            .fillMaxSize()
            .statusBarsPadding()
            .padding(horizontal = 28.dp)
            .verticalScroll(rememberScrollState())
    ) {
        Box(
            contentAlignment = Alignment.Center,
            modifier = Modifier
                .size(110.dp)
                .clip(CircleShape)
                .background(Wrong.copy(alpha = 0.15f))
                .border(2.dp, Wrong.copy(alpha = 0.60f), CircleShape)
        ) {
            Text(
                text = "\u2715",
                style = StellaeTypography.displayLg.copy(
                    color = Wrong,
                    fontSize = 48.sp
                )
            )
        }

        Spacer(modifier = Modifier.height(24.dp))

        Text(
            text = "Defeated",
            style = StellaeTypography.displayLg.copy(
                color = Wrong,
                fontWeight = FontWeight.Bold,
                fontSize = 42.sp
            ),
            textAlign = TextAlign.Center
        )

        Text(
            text = "${boss.name} has prevailed",
            style = StellaeTypography.bodyLg.copy(color = TextSecondary),
            textAlign = TextAlign.Center,
            modifier = Modifier.padding(top = 8.dp, bottom = 20.dp)
        )

        val requiredPct = (boss.requiredAccuracy * 100).toInt()
        val actualPct = if (totalCount > 0) (correctCount * 100 / totalCount) else 0

        Box(
            modifier = Modifier
                .fillMaxWidth()
                .clip(StellaeShapes.md)
                .background(BgCard)
                .border(1.dp, BorderSubtle, StellaeShapes.md)
                .padding(14.dp)
        ) {
            Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
                Text(
                    text = "Required: $requiredPct% accuracy",
                    style = StellaeTypography.bodyMd.copy(color = TextSecondary)
                )
                Text(
                    text = "Your result: $actualPct% ($correctCount / $totalCount correct)",
                    style = StellaeTypography.bodyMd.copy(color = Wrong)
                )
                Spacer(modifier = Modifier.height(4.dp))
                XpProgressBar(
                    progress = actualPct.toFloat() / 100f,
                    modifier = Modifier.fillMaxWidth()
                )
            }
        }

        Spacer(modifier = Modifier.height(32.dp))

        PrimaryButton(
            text = "Try Again",
            onClick = onRetry,
            modifier = Modifier.fillMaxWidth()
        )
        Spacer(modifier = Modifier.height(12.dp))
        SecondaryButton(
            text = "Retreat",
            onClick = onBack,
            modifier = Modifier.fillMaxWidth()
        )
    }
}

