// ── Phase enum ────────────────────────────────────────────────────────────────

private enum class BossPhase { INTRO, CHALLENGE, VICTORY, DEFEAT }

// ── BossScreen ────────────────────────────────────────────────────────────────

/**
 * Boss challenge screen. Loads the challenge by [bossId] from BossChallenge.ALL,
 * presents the quiz, then shows a victory or defeat result.
 *
 * Usage:
 *   BossScreen(
 *       bossId = "domicile_boss",
 *       onBack = { navController.popBackStack() }
 *   )
 */
@Composable
fun BossScreen(
    bossId: String,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    val boss = remember(bossId) { BossChallenge.findById(bossId) }

    if (boss == null) {
        // Fallback for unknown boss ID
        Box(
            contentAlignment = Alignment.Center,
            modifier = modifier
                .fillMaxSize()
                .background(BgDeep)
        ) {
            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                Text(
                    text = "Challenge not found",
                    style = StellaeTypography.bodyLg.copy(color = TextSecondary)
                )
                Spacer(modifier = Modifier.height(16.dp))
                SecondaryButton(text = "Go Back", onClick = onBack)
            }
        }
        return
    }

    val questions = remember(boss) { getBossQuestions(boss) }
    var phase by remember { mutableStateOf(BossPhase.INTRO) }
    var currentIndex by remember { mutableIntStateOf(0) }
    var selectedOption by remember { mutableStateOf<Int?>(null) }
    var isAnswerRevealed by remember { mutableStateOf(false) }
    val answeredCorrectly = remember { mutableStateListOf<Boolean>() }
    var remainingSeconds by remember { mutableIntStateOf(boss.timeLimitSeconds ?: 0) }
    var timerActive by remember { mutableStateOf(false) }

    // Countdown timer
    LaunchedEffect(timerActive) {
        if (timerActive && boss.timeLimitSeconds != null) {
            while (remainingSeconds > 0 && timerActive) {
                delay(1000L)
                remainingSeconds--
            }
            if (remainingSeconds == 0 && timerActive) {
                // Time's up — determine pass/fail
                timerActive = false
                val correct = answeredCorrectly.count { it }
                val accuracy = if (questions.isEmpty()) 0f else correct.toFloat() / questions.size
                phase = if (accuracy >= boss.requiredAccuracy) BossPhase.VICTORY else BossPhase.DEFEAT
            }
        }
    }

    Box(
        modifier = modifier
            .fillMaxSize()
            .background(BgDeep)
    ) {
        StarfieldBackground(starCount = 80)

        when (phase) {
            BossPhase.INTRO -> {
                BossIntroContent(
                    boss = boss,
                    onBegin = {
                        phase = BossPhase.CHALLENGE
                        if (boss.timeLimitSeconds != null) timerActive = true
                    },
                    onBack = onBack
                )
            }

            BossPhase.CHALLENGE -> {
                if (currentIndex < questions.size) {
                    BossChallengeContent(
                        boss = boss,
                        question = questions[currentIndex],
                        questionNumber = currentIndex + 1,
                        totalQuestions = questions.size,
                        answersCorrect = answeredCorrectly.count { it },
                        selectedOption = selectedOption,
                        isRevealed = isAnswerRevealed,
                        remainingSeconds = if (boss.timeLimitSeconds != null) remainingSeconds else null,
                        onOptionSelected = { idx ->
                            if (!isAnswerRevealed) {
                                selectedOption = idx
                                isAnswerRevealed = true
                                answeredCorrectly.add(idx == questions[currentIndex].correctIndex)
                            }
                        },
                        onNext = {
                            val isLast = currentIndex + 1 >= questions.size
                            if (isLast) {
                                timerActive = false
                                val correct = answeredCorrectly.count { it }
                                val accuracy = correct.toFloat() / questions.size
                                phase = if (accuracy >= boss.requiredAccuracy) BossPhase.VICTORY else BossPhase.DEFEAT
                            } else {
                                currentIndex++
                                selectedOption = null
                                isAnswerRevealed = false
                            }
                        }
                    )
                }
            }

            BossPhase.VICTORY -> {
                VictoryContent(
                    boss = boss,
                    correctCount = answeredCorrectly.count { it },
                    totalCount = questions.size,
                    elapsedSeconds = boss.timeLimitSeconds?.minus(remainingSeconds),
                    onBack = onBack
                )
            }

            BossPhase.DEFEAT -> {
                DefeatContent(
                    boss = boss,
                    correctCount = answeredCorrectly.count { it },
                    totalCount = questions.size,
                    onRetry = {
                        currentIndex = 0
                        selectedOption = null
                        isAnswerRevealed = false
                        answeredCorrectly.clear()
                        remainingSeconds = boss.timeLimitSeconds ?: 0
                        phase = BossPhase.CHALLENGE
                        if (boss.timeLimitSeconds != null) timerActive = true
                    },
                    onBack = onBack
                )
            }
        }
    }
}

