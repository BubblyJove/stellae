// ── Challenge quiz ────────────────────────────────────────────────────────────

@Composable
private fun BossChallengeContent(
    boss: BossChallenge,
    question: BossQuestion,
    questionNumber: Int,
    totalQuestions: Int,
    answersCorrect: Int,
    selectedOption: Int?,
    isRevealed: Boolean,
    remainingSeconds: Int?,
    onOptionSelected: (Int) -> Unit,
    onNext: () -> Unit
) {
    val progressFraction = questionNumber.toFloat() / totalQuestions.toFloat()
    val progressAnim by animateFloatAsState(
        targetValue = progressFraction,
        animationSpec = tween(400),
        label = "progress"
    )

    val timerColor = when {
        remainingSeconds == null -> Gold
        remainingSeconds > 20    -> Gold
        remainingSeconds > 10    -> Color(0xFFFBBF24) // amber
        else                     -> Wrong
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .statusBarsPadding()
    ) {
        // Header with title, timer, progress
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .background(BgCard)
                .padding(horizontal = 16.dp, vertical = 12.dp)
        ) {
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween,
                modifier = Modifier.fillMaxWidth()
            ) {
                Column {
                    Text(
                        text = boss.name,
                        style = StellaeTypography.bodySm.copy(color = Gold)
                    )
                    Text(
                        text = "$answersCorrect / $questionNumber-1 correct",
                        style = StellaeTypography.caption.copy(color = TextMuted)
                    )
                }
                if (remainingSeconds != null) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        modifier = Modifier
                            .clip(StellaeShapes.full)
                            .background(timerColor.copy(alpha = 0.12f))
                            .border(1.dp, timerColor.copy(alpha = 0.40f), StellaeShapes.full)
                            .padding(horizontal = 12.dp, vertical = 6.dp)
                    ) {
                        Icon(
                            imageVector = Icons.Default.Timer,
                            contentDescription = null,
                            tint = timerColor,
                            modifier = Modifier.size(14.dp)
                        )
                        Spacer(modifier = Modifier.width(4.dp))
                        Text(
                            text = formatSeconds(remainingSeconds),
                            style = StellaeTypography.bodyMd.copy(
                                color = timerColor,
                                fontWeight = FontWeight.Bold
                            )
                        )
                    }
                }
            }
            Spacer(modifier = Modifier.height(8.dp))
            // Progress bar
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(6.dp)
                    .clip(StellaeShapes.full)
                    .background(BgSurface)
            ) {
                Box(
                    modifier = Modifier
                        .fillMaxWidth(progressAnim)
                        .fillMaxHeight()
                        .clip(StellaeShapes.full)
                        .background(Wrong)
                )
            }
        }

        Column(
            modifier = Modifier
                .fillMaxSize()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            Spacer(modifier = Modifier.height(12.dp))

            // Question number indicator
            Text(
                text = "Question $questionNumber of $totalQuestions",
                style = StellaeTypography.label.copy(color = TextMuted)
            )

            // Question
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(StellaeShapes.xl)
                    .background(BgCard)
                    .border(1.dp, BorderGlow, StellaeShapes.xl)
                    .padding(20.dp)
            ) {
                Text(
                    text = question.text,
                    style = StellaeTypography.displaySm.copy(
                        color = TextPrimary,
                        fontWeight = FontWeight.Bold
                    ),
                    textAlign = TextAlign.Center,
                    modifier = Modifier.fillMaxWidth()
                )
            }

            // Options
            question.options.forEachIndexed { idx, option ->
                val state = when {
                    !isRevealed && selectedOption == idx -> QuizOptionState.DEFAULT
                    isRevealed && idx == question.correctIndex -> QuizOptionState.CORRECT
                    isRevealed && idx == selectedOption && idx != question.correctIndex -> QuizOptionState.WRONG
                    else -> QuizOptionState.DEFAULT
                }
                QuizOption(
                    letter = ('A' + idx).toString(),
                    text = option,
                    state = state,
                    onClick = { onOptionSelected(idx) },
                    modifier = Modifier.fillMaxWidth()
                )
            }

            // Explanation / next button
            AnimatedVisibility(
                visible = isRevealed,
                enter = fadeIn(tween(300)),
                exit = fadeOut()
            ) {
                Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    val isCorrect = selectedOption == question.correctIndex
                    Box(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clip(StellaeShapes.md)
                            .background(if (isCorrect) Correct.copy(alpha = 0.10f) else Wrong.copy(alpha = 0.10f))
                            .border(
                                1.dp,
                                if (isCorrect) Correct.copy(alpha = 0.40f) else Wrong.copy(alpha = 0.40f),
                                StellaeShapes.md
                            )
                            .padding(14.dp)
                    ) {
                        Text(
                            text = if (isCorrect)
                                "Correct! ${question.options[question.correctIndex]}"
                            else
                                "The correct answer is: ${question.options[question.correctIndex]}",
                            style = StellaeTypography.bodyMd.copy(
                                color = if (isCorrect) Correct else Wrong
                            )
                        )
                    }
                    PrimaryButton(
                        text = if (questionNumber < totalQuestions) "Next Question" else "See Results",
                        onClick = onNext,
                        modifier = Modifier.fillMaxWidth()
                    )
                }
            }

            Spacer(modifier = Modifier.height(24.dp))
        }
    }
}

